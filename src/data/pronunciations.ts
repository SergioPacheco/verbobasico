/** Busca a pronúncia de um verbo/tempo/pronome */
export function getPronunciation(
  infinitive: string,
  tense: TenseKey,
  pronoun: Pronoun
): PronunciationEntry | null {
  const verb = pronunciations[infinitive];
  if (!verb) return null;
  const tenseData = verb[tense];
  if (!tenseData) return null;
  return tenseData[pronoun] || null;
}
